// Embeds layouts/*.layout into js/layouts.js and writes dist/twiddler-trainer.html,
// a single self-contained page (all CSS and JS inlined).
//   node tools/build.mjs            -> js/layouts.js + dist/twiddler-trainer.html
//   node tools/build.mjs --fragment -> also dist/fragment.html (no <html>/<head> wrapper)
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const BUILTIN = [{ id: 'backspice', file: 'backspice.layout', name: 'Backspice (left hand)' }];

const entries = BUILTIN.map((b) => ({ ...b, source: readFileSync(join(root, 'layouts', b.file), 'utf8') }));
const known = new Set(BUILTIN.map((b) => b.file));
for (const f of readdirSync(join(root, 'layouts'))) {
  if (f.endsWith('.layout') && !known.has(f)) console.warn('note: layouts/' + f + ' is not listed in BUILTIN');
}
writeFileSync(
  join(root, 'js/layouts.js'),
  '/* Generated by tools/build.mjs from layouts/*.layout. Do not edit by hand. */\n' +
    '(function (root) {\n  (root.T4 = root.T4 || {}).BUILTIN_LAYOUTS = ' +
    JSON.stringify(entries.map(({ id, name, source }) => ({ id, name, source })), null, 2).replace(/\n/g, '\n  ') +
    ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n'
);

const html = readFileSync(join(root, 'index.html'), 'utf8');
const inlined = html
  .replace(/<link rel="stylesheet" href="(css\/[^"]+)">/g, (_, p) => '<style>\n' + readFileSync(join(root, p), 'utf8') + '</style>')
  .replace(/<script src="(js\/[^"]+)"><\/script>/g, (_, p) => '<script>\n' + readFileSync(join(root, p), 'utf8').replace(/<\/script/gi, '<\\/script') + '</script>');
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/twiddler-trainer.html'), inlined);
if (process.argv.includes('--fragment')) {
  const head = inlined.match(/<head>([\s\S]*?)<\/head>/)[1].replace(/<meta charset[^>]*>|<meta name="viewport"[^>]*>/g, '');
  const body = inlined.match(/<body>([\s\S]*)<\/body>/)[1];
  writeFileSync(join(root, 'dist/fragment.html'), head.trim() + '\n' + body.trim() + '\n');
}
console.log('built js/layouts.js and dist/twiddler-trainer.html');
